"""
Generate frontend mock-mode data from the REAL project SQLite database (read-only).

    python frontend/scripts/generate_mock_data.py          (run from repo root)

Outputs (all inside frontend/src/services/mock/):
  - summaries.js         -> funnel_summary rows (ALL + 5 monthly periods), 10 API fields
  - replaySessions.js    -> 100 curated replay sessions (25 public API fields) + SAFE events only
                            (before_first_cart / at_first_cart_second / same_second_other)
  - replayOutcomes.js    -> actual outcome + post-cart events. Lazily imported by the frontend
                            ONLY when the user clicks "Reveal outcome".

Privacy / leakage rules enforced here:
  - user_id and raw user_session are never written.
  - target_purchased_after_cart is never written to the safe module; it is exposed only as
    `actual_outcome` inside the lazily-loaded outcomes module.
  - Session ids rs_001..rs_100 are assigned by ascending user_session (matches API_CONTRACT rs_001).
"""
import json
import sqlite3
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
DB = ROOT / "data" / "dealmind.db"
OUT = Path(__file__).resolve().parents[1] / "src" / "services" / "mock"

SUMMARY_FIELDS = [
    "period", "total_valid_sessions", "sessions_with_view", "sessions_with_cart",
    "sessions_with_purchase", "overall_purchase_rate_pct", "view_to_purchase_rate_pct",
    "session_cart_abandonment_rate_pct", "historical_aov_pos", "historical_aov_signed",
]

SESSION_FIELDS = [
    "session_start", "first_cart_time", "cart_product_ids_at_first_cart_sec",
    "cart_category_ids_at_first_cart_sec", "seconds_to_first_cart", "views_before_cart",
    "has_view_before_cart", "unique_products_viewed_before_cart",
    "unique_categories_viewed_before_cart", "unique_brands_viewed_before_cart",
    "removes_before_cart", "unique_products_removed_before_cart",
    "cart_events_at_first_cart_sec", "unique_products_carted_at_first_cart_sec",
    "has_multi_products_at_first_cart_sec", "avg_cart_price_at_first_cart_sec",
    "avg_viewed_price_before_cart", "max_viewed_price_before_cart", "price_ratio_cart_to_view",
    "any_cart_brand_at_first_cart_sec", "hour_of_day_utc", "day_of_week_utc",
    "user_prior_sessions", "user_prior_purchase_sessions",
]

EVENT_FIELDS = ["id", "event_time", "event_type", "product_id", "category_id",
                "category_code", "brand", "price", "event_phase"]
SAFE_PHASES = {"before_first_cart", "at_first_cart_second", "same_second_other"}

HEADER = "// AUTO-GENERATED by frontend/scripts/generate_mock_data.py from data/dealmind.db (read-only).\n// Do not edit by hand.\n"


def js(obj, pretty=False):
    if pretty:
        return json.dumps(obj, indent=2, ensure_ascii=False)
    # one record per line keeps the bundle small but still diff-friendly
    if isinstance(obj, list):
        return "[\n" + ",\n".join(json.dumps(x, ensure_ascii=False, separators=(",", ":")) for x in obj) + "\n]"
    if isinstance(obj, dict):
        return "{\n" + ",\n".join(f"{json.dumps(k)}:{json.dumps(v, ensure_ascii=False, separators=(',', ':'))}"
                                  for k, v in obj.items()) + "\n}"
    return json.dumps(obj, ensure_ascii=False)


def main():
    con = sqlite3.connect(f"file:{DB.as_posix()}?mode=ro", uri=True)
    con.row_factory = sqlite3.Row
    OUT.mkdir(parents=True, exist_ok=True)

    # ---- summaries -------------------------------------------------------
    summaries = {}
    for r in con.execute(f"SELECT {', '.join(SUMMARY_FIELDS)} FROM funnel_summary ORDER BY period"):
        summaries[r["period"]] = {k: r[k] for k in SUMMARY_FIELDS}
    (OUT / "summaries.js").write_text(
        HEADER + "// Source table: funnel_summary\nexport const MOCK_SUMMARIES = " + js(summaries) + "\n",
        encoding="utf-8")

    # ---- sessions --------------------------------------------------------
    rows = list(con.execute("SELECT * FROM replay_sessions ORDER BY user_session ASC"))
    sessions, safe_events, outcomes = [], {}, {}
    for i, r in enumerate(rows, start=1):
        sid = f"rs_{i:03d}"
        item = {"id": sid}
        for k in SESSION_FIELDS:
            v = r[k]
            if k == "user_prior_purchase_sessions" and v is not None:
                v = int(v)
            item[k] = v
        sessions.append(item)

        evs = con.execute(
            "SELECT * FROM replay_session_events WHERE user_session = ? ORDER BY event_time, id",
            (r["user_session"],)).fetchall()
        safe_events[sid] = [{k: e[k] for k in EVENT_FIELDS} for e in evs if e["event_phase"] in SAFE_PHASES]
        outcomes[sid] = {
            "id": sid,
            "actual_outcome": int(r["target_purchased_after_cart"]),
            "events": [{k: e[k] for k in EVENT_FIELDS} for e in evs if e["event_phase"] not in SAFE_PHASES],
        }

    (OUT / "replaySessions.js").write_text(
        HEADER
        + "// 100 curated February 2020 (test split) replay sessions. Public fields + safe pre-cart events only.\n"
        + "export const MOCK_REPLAY_SESSIONS = " + js(sessions) + "\n\n"
        + "export const MOCK_REPLAY_EVENTS = " + js(safe_events) + "\n",
        encoding="utf-8")

    (OUT / "replayOutcomes.js").write_text(
        HEADER
        + "// HIDDEN outcome data. Loaded lazily via dynamic import() ONLY after the user clicks \"Reveal outcome\".\n"
        + "export const MOCK_REPLAY_OUTCOMES = " + js(outcomes) + "\n",
        encoding="utf-8")

    print(f"summaries: {len(summaries)} periods | sessions: {len(sessions)} | "
          f"safe events: {sum(len(v) for v in safe_events.values())} | "
          f"post-cart events: {sum(len(v['events']) for v in outcomes.values())}")
    print("rs_001:", {k: sessions[0][k] for k in ("session_start", "seconds_to_first_cart", "views_before_cart",
                                                   "avg_cart_price_at_first_cart_sec", "price_ratio_cart_to_view",
                                                   "day_of_week_utc")})


if __name__ == "__main__":
    main()
